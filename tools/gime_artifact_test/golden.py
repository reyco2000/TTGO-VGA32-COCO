#!/usr/bin/env python3
# An independent model of MAME's artifacter (mc6847.h artifacter::update_colors()
# and artifact_correction, as the mame-coco3-ttgovga port renders it), written
# from those sources and not from src/core/gime_artifact.h. Prints golden.h:
#   python3 golden.py > golden.h
F=[157,0,157, 0,157,0, 1000,824,1000, 824,1000,824, 706,236,118, 0,197,471, 1000,550,393, 275,785,1000, 0,500,1000, 1000,500,0, 1000,942,785, 393,942,1000, 236,0,0, 0,0,236]
C=[0,0,0,0,0,6,0,2,5,7,5,7,1,3,1,11,8,6,8,14,8,9,8,9,4,4,4,15,12,12,12,15,5,13,5,13,13,0,13,2,10,10,10,10,10,15,10,11,3,1,3,1,15,9,15,9,11,11,11,11,15,15,15,15,14,0,14,0,14,6,14,2,0,7,0,7,1,3,1,11,9,6,9,14,9,9,9,9,15,4,15,15,12,12,12,15,2,13,2,13,2,0,2,2,10,10,10,10,10,15,10,11,12,1,12,1,12,9,12,9,15,11,15,11,15,15,15,15]
def idx(r,g,b): return ((r&2)<<4)|((g&2)<<3)|((b&2)<<2)|((r&1)<<2)|((g&1)<<1)|(b&1)
def q(x): return (x*3+127)//255
def mix(mode,a,b):
    out={0: idx(*map(q,a)), 15: idx(*map(q,b))}
    for i in range(1,15):
        f=F[((i-1)^(mode&1))*3:][:3]
        out[i]=idx(*[q((a[k]*(1000-f[k])+b[k]*f[k]+500)//1000) for k in range(3)])
    return out
def line(src,mode,a,b,border_is_c1):
    cols=mix(mode,a,b); bb=0xFF if border_is_c1 else 0; prev=bb&3; res=[]
    for i,cur in enumerate(src):
        nxt=src[i+1] if i+1<len(src) else bb
        w=(prev<<16)|(cur<<8)|nxt
        for sh in (12,10,8,6):
            v=((w>>sh)&0x3F)*2; res+=[cols[C[v]]]*2+[cols[C[v+1]]]*2
        prev=cur&3
    return res
def arr(name,v): print('static const uint8_t %s[%d] = {%s};'%(name,len(v),','.join(str(x) for x in v)))
print('// Generated by golden.py; do not edit.')
src=[0x55,0xAA,0x0F,0xF0,0x33,0xCC,0x00,0xFF]
arr('k_golden_src',src)
for mode in (1,2):
    for bs in (0,1):
        arr('k_golden_m%d_b%d'%(mode,bs), line(src,mode,(0,0,0),(255,255,255),bs))   # black, white
arr('k_golden_gr', line(src,1,(0,255,0),(255,0,0),0))                                # green, red
